using Autodesk.Revit.DB;
using DxfToRevit.Revit.Columns;
using DxfToRevit.Revit.Common;
using DxfToRevit.Revit.Import;
using DxfToRevit.Revit.Openings;
using DxfToRevit.Revit.Walls;
using System.IO;

namespace DxfToRevit.Revit.Columns;

/// <summary>
/// Builds a loadable column family (.rfa) from a freeform column section and loads it into the project.
/// </summary>
/// <remarks>
/// The family is derived from the Revit column template (<c>Metric Column.rft</c>). Its solid is locked
/// to the lower and upper reference levels, so the placed column can be bound to Base/Top Level.
/// <list type="number">
/// <item><description>When the template contains a (locked) extrusion, only its sketch (profile) is replaced; the locks are kept.</description></item>
/// <item><description>Otherwise a new extrusion is created and its top and bottom faces are aligned and locked to the levels.</description></item>
/// </list>
/// Each distinct section produces one family; the name is derived from the section
/// (see <see cref="FreeformColumnFamilyNaming"/>).
/// </remarks>
internal sealed class RevitFreeformColumnFamilyBuilder
{
    /// <summary>Column family templates, in order of preference.</summary>
    public static readonly IReadOnlyList<string> TemplateFileNames = new[] { "Metric Column.rft", "Column.rft" };

    private readonly Document _project;
    private readonly Dictionary<string, FamilySymbol> _cache = new(StringComparer.OrdinalIgnoreCase);
    private string? _templatePath;
    private bool _templateSearched;

    /// <summary>Creates the builder for a project document.</summary>
    /// <param name="project">Project the families are loaded into.</param>
    /// <exception cref="System.ArgumentNullException"><paramref name="project"/> is <c>null</c>.</exception>
    public RevitFreeformColumnFamilyBuilder(Document project)
    {
        _project = project ?? throw new ArgumentNullException(nameof(project));
    }

    /// <summary>
    /// Returns the family type for the section, building and loading the family when needed.
    /// A family generated by an earlier import is reused.
    /// </summary>
    /// <param name="profileFeet">Section vertices relative to the placement point (feet).</param>
    /// <param name="error">Reason when no type could be provided.</param>
    /// <returns>The family type, or <c>null</c>.</returns>
    public FamilySymbol? GetOrCreate(IReadOnlyList<(double X, double Y)> profileFeet, out string? error)
    {
        error = null;
        ArgumentNullException.ThrowIfNull(profileFeet);
        if (profileFeet.Count < 3)
        {
            error = "Freeform column profile needs at least 3 vertices.";
            return null;
        }

        string familyName = FreeformColumnFamilyNaming.FamilyName(
            profileFeet.Select(p => (LengthUnitConverter.FeetToMm(p.X), LengthUnitConverter.FeetToMm(p.Y))).ToList());

        if (_cache.TryGetValue(familyName, out FamilySymbol? cached) && cached.IsValidObject)
            return cached;

        // Reuse a family generated by an earlier import when it is already in the project.
        FamilySymbol? existing = FindFirstSymbol(familyName);
        if (existing is not null)
            return _cache[familyName] = existing;

        string? template = FindTemplate();
        if (template is null)
        {
            error = "Column family template (Metric Column.rft) was not found.";
            return null;
        }

        string? rfaPath = BuildFamilyFile(template, familyName, profileFeet, out error);
        if (rfaPath is null)
            return null;

        try
        {
            using (var tx = RevitChangeScope.Start(_project, "DxfToRevit Load Freeform Column Family"))
            {
                _project.LoadFamily(rfaPath, new OverwriteFamilyLoadOptions(), out Family _);
                tx.Commit();
            }

            FamilySymbol? symbol = FindFirstSymbol(familyName);
            if (symbol is null)
            {
                error = $"Freeform column family '{familyName}' was created but could not be loaded.";
                return null;
            }

            return _cache[familyName] = symbol;
        }
        catch (Exception ex)
        {
            error = $"Could not load freeform column family '{familyName}': {ex.Message}";
            return null;
        }
        finally
        {
            TryDelete(rfaPath);
        }
    }

    /// <summary>First type of the family with the given name in the project, or <c>null</c>.</summary>
    private FamilySymbol? FindFirstSymbol(string familyName)
    {
        Family? family = new FilteredElementCollector(_project)
            .OfClass(typeof(Family))
            .Cast<Family>()
            .FirstOrDefault(f => string.Equals(f.Name, familyName, StringComparison.OrdinalIgnoreCase));

        ElementId? id = family?.GetFamilySymbolIds().FirstOrDefault();
        return id is null ? null : _project.GetElement(id) as FamilySymbol;
    }

    /// <summary>
    /// Finds the column family template in the Revit template folder or the default
    /// <c>Family Templates</c> folder (searched once per builder).
    /// </summary>
    private string? FindTemplate()
    {
        if (_templateSearched)
            return _templatePath;

        _templateSearched = true;
        var app = _project.Application;
        var roots = new List<string?>();
        try { roots.Add(app.FamilyTemplatePath); } catch { /* not configured: fall back to the default folder */ }
        roots.Add(Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData),
            "Autodesk", $"RVT {app.VersionNumber}", "Family Templates"));

        _templatePath = LibraryFileSearch.FindFirst(roots, TemplateFileNames);
        return _templatePath;
    }

    /// <summary>Creates the family document, builds the geometry and saves it to a temporary folder.</summary>
    /// <returns>Path of the saved .rfa, or <c>null</c> with <paramref name="error"/> set.</returns>
    private string? BuildFamilyFile(
        string templatePath, string familyName, IReadOnlyList<(double X, double Y)> profileFeet, out string? error)
    {
        error = null;
        Document? family = null;
        try
        {
            family = _project.Application.NewFamilyDocument(templatePath);
            if (family is null)
            {
                error = "Could not create a family document from the column template.";
                return null;
            }

            Extrusion? templateExtrusion = new FilteredElementCollector(family)
                .OfClass(typeof(Extrusion))
                .Cast<Extrusion>()
                .FirstOrDefault(e => e.IsSolid);

            bool ok = templateExtrusion is not null
                ? TryReplaceProfile(family, templateExtrusion, profileFeet, out error)
                : TryCreateLockedExtrusion(family, profileFeet, out error);
            if (!ok)
                return null;

            string dir = Path.Combine(Path.GetTempPath(), "DxfToRevit", "Families");
            Directory.CreateDirectory(dir);
            string path = Path.Combine(dir, familyName + ".rfa");
            family.SaveAs(path, new SaveAsOptions { OverwriteExistingFile = true });
            return path;
        }
        catch (Exception ex)
        {
            error = $"Freeform column family build failed: {ex.Message}";
            return null;
        }
        finally
        {
            try { family?.Close(false); } catch { /* the family document may already be closed */ }
        }
    }

    /// <summary>
    /// Deletes the lines of the template extrusion sketch and draws the new section.
    /// The extrusion's top and bottom locks (alignments to the levels) do not depend on the
    /// sketch, so they are kept.
    /// </summary>
    private static bool TryReplaceProfile(
        Document family, Extrusion extrusion, IReadOnlyList<(double X, double Y)> profileFeet, out string? error)
    {
        error = null;
        Sketch sketch = extrusion.Sketch;
        SketchPlane sketchPlane = sketch.SketchPlane;
        double z = sketchPlane.GetPlane().Origin.Z;

        if (!TryBuildCurves(profileFeet, z, out List<Curve> curves, out error))
            return false;

        using var scope = new SketchEditScope(family, "DxfToRevit Freeform Profile");
        scope.Start(sketch.Id);

        using (var tx = new Transaction(family, "DxfToRevit Replace Profile"))
        {
            tx.Start();
            var oldCurves = sketch.GetAllElements()
                .Where(id => family.GetElement(id) is CurveElement)
                .ToList();
            if (oldCurves.Count > 0)
                family.Delete(oldCurves);

            foreach (Curve curve in curves)
                family.FamilyCreate.NewModelCurve(curve, sketchPlane);

            tx.Commit();
        }

        scope.Commit(new WarningSwallower());
        return true;
    }

    /// <summary>
    /// Used when the template has no extrusion: creates an extrusion on the lower level and
    /// aligns and locks its top and bottom faces to the levels in an elevation view.
    /// </summary>
    private static bool TryCreateLockedExtrusion(
        Document family, IReadOnlyList<(double X, double Y)> profileFeet, out string? error)
    {
        error = null;
        List<Level> levels = new FilteredElementCollector(family)
            .OfClass(typeof(Level))
            .Cast<Level>()
            .OrderBy(l => l.Elevation)
            .ToList();
        if (levels.Count < 2)
        {
            error = "Column template has no lower/upper reference levels to bind the column to.";
            return false;
        }

        Level lower = levels[0];
        Level upper = levels[^1];

        View? elevation = new FilteredElementCollector(family)
            .OfClass(typeof(View))
            .Cast<View>()
            .FirstOrDefault(v => !v.IsTemplate && v.ViewType == ViewType.Elevation);
        if (elevation is null)
        {
            error = "Column template has no elevation view for locking the extrusion.";
            return false;
        }

        if (!TryBuildCurves(profileFeet, lower.Elevation, out List<Curve> curves, out error))
            return false;

        using var tx = new Transaction(family, "DxfToRevit Create Freeform Extrusion");
        var options = tx.GetFailureHandlingOptions();
        options.SetFailuresPreprocessor(new WarningSwallower());
        tx.SetFailureHandlingOptions(options);
        tx.Start();

        SketchPlane plane = SketchPlane.Create(family, lower.Id);
        var loop = new CurveArray();
        foreach (Curve c in curves)
            loop.Append(c);
        var profile = new CurveArrArray();
        profile.Append(loop);

        Extrusion extrusion = family.FamilyCreate.NewExtrusion(
            true, profile, plane, upper.Elevation - lower.Elevation);
        family.Regenerate();

        if (!TryFindCapFaces(extrusion, out PlanarFace? top, out PlanarFace? bottom))
        {
            tx.RollBack();
            error = "Could not find the top/bottom faces of the freeform extrusion.";
            return false;
        }

        family.FamilyCreate.NewAlignment(elevation, upper.GetPlaneReference(), top!.Reference);
        family.FamilyCreate.NewAlignment(elevation, lower.GetPlaneReference(), bottom!.Reference);

        tx.Commit();
        return true;
    }

    /// <summary>Finds the top (normal +Z) and bottom (normal -Z) planar faces of the extrusion.</summary>
    private static bool TryFindCapFaces(Extrusion extrusion, out PlanarFace? top, out PlanarFace? bottom)
    {
        top = bottom = null;
        var options = new Options { ComputeReferences = true };
        foreach (GeometryObject obj in extrusion.get_Geometry(options))
        {
            if (obj is not Solid solid)
                continue;

            foreach (Face face in solid.Faces)
            {
                if (face is not PlanarFace pf)
                    continue;
                if (pf.FaceNormal.Z > 0.9)
                    top = pf;
                else if (pf.FaceNormal.Z < -0.9)
                    bottom = pf;
            }
        }

        return top?.Reference is not null && bottom?.Reference is not null;
    }

    /// <summary>Builds the closed profile lines at elevation <paramref name="z"/>; fails on zero-length edges.</summary>
    private static bool TryBuildCurves(
        IReadOnlyList<(double X, double Y)> profileFeet, double z, out List<Curve> curves, out string? error)
    {
        error = null;
        curves = new List<Curve>(profileFeet.Count);
        for (int i = 0; i < profileFeet.Count; i++)
        {
            var a = profileFeet[i];
            var b = profileFeet[(i + 1) % profileFeet.Count];
            var start = new XYZ(a.X, a.Y, z);
            var end = new XYZ(b.X, b.Y, z);
            if (start.DistanceTo(end) < 1e-6)
            {
                error = "Freeform column outline contains a zero-length edge.";
                return false;
            }

            curves.Add(Line.CreateBound(start, end));
        }

        return true;
    }

    /// <summary>Deletes a temporary file, ignoring failures.</summary>
    private static void TryDelete(string path)
    {
        try { File.Delete(path); } catch { /* temporary file; failing to delete it is harmless */ }
    }

    /// <summary>Deletes warnings silently; errors are left to Revit.</summary>
    private sealed class WarningSwallower : IFailuresPreprocessor
    {
        /// <inheritdoc />
        public FailureProcessingResult PreprocessFailures(FailuresAccessor failuresAccessor)
        {
            foreach (FailureMessageAccessor message in failuresAccessor.GetFailureMessages())
            {
                if (message.GetSeverity() == FailureSeverity.Warning)
                    failuresAccessor.DeleteWarning(message);
            }

            return FailureProcessingResult.Continue;
        }
    }

    /// <summary>Overwrites an existing family with the same name, including parameter values.</summary>
    private sealed class OverwriteFamilyLoadOptions : IFamilyLoadOptions
    {
        /// <inheritdoc />
        public bool OnFamilyFound(bool familyInUse, out bool overwriteParameterValues)
        {
            overwriteParameterValues = true;
            return true;
        }

        /// <inheritdoc />
        public bool OnSharedFamilyFound(
            Family sharedFamily, bool familyInUse, out FamilySource source, out bool overwriteParameterValues)
        {
            source = FamilySource.Family;
            overwriteParameterValues = true;
            return true;
        }
    }
}
